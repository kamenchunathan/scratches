use bevy::{
    asset::{Asset, uuid},
    ecs::component::Component,
    math::Vec2,
    reflect::Reflect,
};
use serde::{Deserialize, Serialize};

mod animator;
pub mod loader;

/// Unique identifier for a critter instance
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, Reflect)]
pub struct CritterId(pub uuid::Uuid);

impl CritterId {
    pub fn new() -> Self {
        Self(uuid::Uuid::new_v4())
    }
}

#[derive(Debug, Clone, Serialize, Deserialize, Reflect)]
pub struct UiAnimations {
    /// Looping preview shown in the adopt gallery.
    pub preview: usize,

    /// Played on the adoption confirmation
    pub celebrate: usize,

    /// Looping idle shown after adoption in the UI.
    pub idle: usize,
}

